const dicts = { en, es };
let lang = 'en';
const listeners = new Set();

try {
  const saved = localStorage.getItem('lang');
  if (saved === 'es' || saved === 'en') lang = saved;
  else if (navigator.language?.toLowerCase().startsWith('es')) lang = 'es';
} catch { /* storage unavailable */ }

export const i18n = {
  get lang() { return lang; },
  t(key) { return dicts[lang][key] ?? dicts.en[key] ?? key; },
  locale() { return lang === 'es' ? 'es-ES' : 'en-GB'; },
  set(next) {
    lang = next;
    try { localStorage.setItem('lang', next); } catch { /* ignore */ }
    this.apply();
    listeners.forEach((fn) => fn(lang));
  },
  onChange(fn) { listeners.add(fn); },
  apply(root = document) {
    document.documentElement.lang = lang;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = this.t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = this.t(el.dataset.i18nHtml); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', this.t(el.dataset.i18nAria)); });
  },
};
